# Context-specific overrides: (context, source) -> translation
CTX = {
    ("ChecksumDialog", "Selection"): "選取範圍",
    ("MainWindow", "Big endian"): "大端序",
    ("MainWindow", "Edit"): "編輯",
    ("FindDialog", "Find &Next"): "找下一個(&N)",
}


def main():
    tree = ET.parse(TS)
    root = tree.getroot()
    root.set("language", "zh_TW")
    missing = []
    for ctx in root.findall("context"):
        cname = ctx.find("name").text
        for msg in ctx.findall("message"):
            src = msg.find("source").text or ""
            tr = CTX.get((cname, src), T.get(src))
            tel = msg.find("translation")
            if tel is None:
                tel = ET.SubElement(msg, "translation")
            if tr is None:
                missing.append(f"{cname}: {src!r}")
                continue
            for child in list(tel):
                tel.remove(child)
            tel.attrib.pop("type", None)
            if msg.get("numerus") == "yes":
                tel.text = None
                nf = ET.SubElement(tel, "numerusform")
                nf.text = tr
            else:
                tel.text = tr
    tree.write(TS, encoding="utf-8", xml_declaration=True)
    if missing:
        print("Missing translations:\n  " + "\n  ".join(missing))
        return 1
    print("All strings translated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
